class WatershedRepository:
    """Responsible for all database interactions."""
    def __init__(self, engine: Engine):
        self.engine = engine

    def get_thuc_id_by_xy(self, x: float, y: float) -> int:
        """Returns the thuc_id for which the coordinates belong to."""
        sql = sql_text(f"SELECT thuc_near_run_id_tr({x},{y})")
        # No 'with' block needed here, as passing the engine to pandas
        # handles connection lifecycle automatically.
        thuc = pd.read_sql(sql, self.engine)
        return thuc.iloc[0].values[0]

    def get_outlet_xy_from_thuc_id_and_reach_id(self, thuc_id: int, reach_id: int = 2) -> Tuple[float, float]:
        """Returns the x and y coordinates of centroid of the reach_id in thuc_id."""
        sql = sql_text(
            f"""SELECT ST_X(ST_Centroid(ST_Collect(ST_Transform(geom, 4326)))) AS lon, 
                ST_Y(ST_Centroid(ST_Collect(ST_Transform(geom, 4326)))) AS lat 
            FROM thuc_{thuc_id}_annagnps_reach_ids
            WHERE dn = {reach_id}
            """
        )
        df = pd.read_sql(sql, self.engine)
        x, y = df["lon"].to_list()[0], df["lat"].to_list()[0]
        return x, y

    def query_cells(self, thuc_id: int, lon: float, lat: float, perform_data_checks: bool = True) -> Tuple[gpd.GeoDataFrame, pd.DataFrame, List[int]]:
        """Queries and processes cell geometry and data."""
        cells_query = f"SELECT geom, cell_id FROM thuc_cell_geo_tr({lon},{lat}, '{thuc_id}')"
        with self.engine.connect() as conn:
            cells_geometry = gpd.read_postgis(sql=sql_text(cells_query), con=conn, geom_col='geom')
        
        cells_geometry = cells_geometry.dissolve(by='cell_id').reset_index()
        cells_list = cells_geometry['cell_id'].unique().tolist()
        
        cells_string = ", ".join(map(str, cells_list))
        cells_data_section_sql = f"SELECT * FROM thuc_{thuc_id}_annagnps_cell_data_section WHERE cell_id in ({cells_string})"
        
        with self.engine.connect() as conn:
            df_cells = pd.read_sql_query(sql=sql_text(cells_data_section_sql), con=conn)
        
        # ... rest of implementation from original query_cells ...
        columns = [col for col in df_cells.columns if col not in ['soil_id_annagnps_valid']]
        df_cells = df_cells[columns]
        if perform_data_checks:
            df_cells = annagnps.check_cell_data(df_cells)
        cells_geometry = cells_geometry.merge(df_cells, on='cell_id')
        
        return cells_geometry, df_cells, cells_list

    def query_reaches(self, thuc_id: int, lon: float, lat: float) -> Tuple[gpd.GeoDataFrame, pd.DataFrame, List[int]]:
        """Queries and processes reach geometry and data."""
        reaches_query = f"SELECT geom, reach_id FROM thuc_reach_geo_tr({lon},{lat}, '{thuc_id}')"
        with self.engine.connect() as conn:
            reaches_geometry = gpd.read_postgis(sql=sql_text(reaches_query), con=conn, geom_col='geom')

        # ... rest of implementation from original query_reaches ...
        reaches_geometry = reaches_geometry.dissolve(by='reach_id').reset_index()
        reaches_list = reaches_geometry['reach_id'].unique().tolist()
        reaches_string = ", ".join(map(str, reaches_list))
        reaches_data_section_sql = f"SELECT * FROM thuc_{thuc_id}_annagnps_reach_data_section WHERE reach_id in ({reaches_string})"

        with self.engine.connect() as conn:
            df_reaches = pd.read_sql_query(sql=sql_text(reaches_data_section_sql), con=conn)

        reaches_geometry = reaches_geometry.merge(df_reaches, on='reach_id')
        df_reaches_valid = annagnps.make_df_reaches_valid(df_reaches)
        
        return reaches_geometry, df_reaches_valid, reaches_list

    def query_soil(self, soil_ids_list: List[str], perform_data_checks: bool = True) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
        """Queries soil, soil layers, and raw soil data."""
        soil_ids_string = ", ".join(map(str, soil_ids_list))
        
        query_soil = f"""SELECT * FROM usa_valid_soil_data WHERE "Soil_ID" in ({soil_ids_string})"""
        query_soil_layers = f"""SELECT * FROM usa_valid_soil_layers_data WHERE "Soil_ID" in ({soil_ids_string})"""
        query_raw = f"""SELECT * FROM raw_nrcs_soil_data WHERE "mukey" in ({soil_ids_string})"""
        
        with self.engine.connect() as conn:
            df_soil_data = pd.read_sql_query(sql=sql_text(query_soil), con=conn)
            df_soil_layers_data = pd.read_sql_query(sql=sql_text(query_soil_layers), con=conn).sort_values(by=['Soil_ID','Layer_Number'])
            df_raw = pd.read_sql_query(sql=sql_text(query_raw), con=conn)
            
        # ... rest of implementation from original query_soil ...
        if perform_data_checks:
            df_soil_data = annagnps.check_soil(df_soil_data)
            df_soil_layers_data = annagnps.check_soil_layers(df_soil_layers_data)
        
        return df_soil_data, df_soil_layers_data, df_raw

