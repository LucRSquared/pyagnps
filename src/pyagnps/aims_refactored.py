class AnnAGNPSInputWriter:
    """Responsible for writing all output files to disk."""
    def __init__(self, config: AIMSWatershedConfig):
        self.config = config
        self.input_folders: Dict[str, Path] = {}

    def make_watershed_input_dirs(self) -> Dict[str, Path]:
        """Creates the AnnAGNPS directory structure."""
        subdirs = ['general', 'climate', 'simulation', 'watershed']
        if self.config.export_gis:
            subdirs.append('GIS')
        
        folder_paths = annagnps.make_annagnps_inputs_dirs(self.config.output_folder, subdirs=subdirs)
        
        self.input_folders = {dir_name: path for dir_name, path in zip(subdirs, folder_paths)}
        return self.input_folders

    def write_dataframe(self, file_path: Path, df: pd.DataFrame, **kwargs):
        """Generic dataframe writer that respects config.overwrite."""
        if not file_path.exists() or self.config.overwrite:
            if not df.empty:
                df.to_csv(file_path, index=False, **kwargs)

    def write_control_file(self, file_path: Path, data_dict: Dict):
        """Generic control file writer that respects config.overwrite."""
        if not file_path.exists() or self.config.overwrite:
            write_csv_control_file_from_dict(data_dict, output_path=file_path)

    def write_gis_files(self, cells_geometry: gpd.GeoDataFrame, reaches_geometry: gpd.GeoDataFrame):
        """Writes GIS output files."""
        if self.config.export_gis and 'GIS' in self.input_folders:
            gis_dir = self.input_folders['GIS']
            if not (gis_dir / 'cells_geometry.gpkg').exists() or self.config.overwrite:
                cells_geometry.to_file(gis_dir / 'cells_geometry.gpkg', driver='GPKG', index=False)
            if not (gis_dir / 'reaches_geometry.gpkg').exists() or self.config.overwrite:
                reaches_geometry.to_file(gis_dir / 'reaches_geometry.gpkg', driver='GPKG', index=False)

    def write_climate_files(self, climate_dataframes: Dict[str, pd.DataFrame], climate_station_metadata: Dict):
        """Writes all climate_daily and climate_station files."""
        climate_dir = self.input_folders['climate']
        
        for clim_id, df in climate_dataframes.items():
            if clim_id == 'global':
                daily_path = climate_dir / "climate_daily.csv"
                station_path = climate_dir / "climate_station.csv"
            else:
                daily_path = climate_dir / f"climate_daily_{clim_id}.csv"
                station_path = climate_dir / f"climate_station_{clim_id}.csv"

            self.write_dataframe(daily_path, df, float_format="%.3f")
            
            station_meta = climate_station_metadata[clim_id]
            station_meta['output_filepath'] = station_path
            
            if not station_path.exists() or self.config.overwrite:
                climate.generate_climate_station_file(**station_meta)

    def write_master_file(self, master_file_dict: Dict[str, str]):
        """Writes the annagnps_master.csv and AnnAGNPS.fil files."""
        master_path = self.config.output_folder / 'annagnps_master.csv'
        
        # Remove ignored entries
        master_file_dict = {k: v for k, v in master_file_dict.items() if v != 'ignore'}

        df_master = pd.DataFrame({
            'Data Section ID': master_file_dict.keys(),
            'File Name': master_file_dict.values()
        })
        
        self.write_dataframe(master_path, df_master)

        # AnnAGNPS.fil file
        annagnps_fil = self.config.output_folder / 'AnnAGNPS.fil'
        if not annagnps_fil.exists() or self.config.overwrite:
            annagnps_fil.write_text('annagnps_master.csv')

