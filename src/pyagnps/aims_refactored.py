def open_creds_dict(path_to_json_creds: Path) -> Dict:
    """Safely opens and reads a JSON credentials file."""
    with open(path_to_json_creds, "r") as f:
        credentials = json.load(f)
        return credentials
    
def create_db_url_object(credentials: Dict) -> URL:
    """Creates a SQLAlchemy URL object from a credentials dictionary."""
    if isinstance(credentials, (str, Path)):
        credentials = open_creds_dict(Path(credentials))

    return URL.create(
        "postgresql",
        username=credentials["user"],
        password=credentials["password"],
        host=credentials["host"],
        port=credentials["port"],
        database=credentials["database"],
    )

