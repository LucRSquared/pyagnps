class AIMSWatershed:
    def __init__(self, path_to_json_creds: Path, config: AIMSWatershedConfig):
        self.config = config
        self.path_to_json_creds = path_to_json_creds
        
        print(f"Initializing watershed at output folder: {self.config.output_folder}")

        # Setup Database Engine
        credentials = open_creds_dict(path_to_json_creds)
        url_object = create_db_url_object(credentials)
        self.engine = create_engine(url_object, pool_size=30, max_overflow=70, pool_timeout=120, pool_recycle=1800)

        # Initialize components
        self.repository = WatershedRepository(self.engine)
        self.asset_loader = StaticAssetLoader()
        self.climate_processor = ClimateProcessor(self.config, self.repository)
        self.input_writer = AnnAGNPSInputWriter(self.config)

        # Internal state for generated data
        self.bounds: Optional[gpd.GeoDataFrame] = None
        self.master_file_dict: Dict[str, str] = {}
        self.watershed_data_dict: Dict[str, Any] = {}

        # Initial setup
        self._check_outlet_coords()

    def set_metadata(self, config: AIMSWatershedConfig):
        """Replaces the entire configuration object."""
        self.config = config
        # Re-initialize components that depend on config
        self.climate_processor = ClimateProcessor(self.config, self.repository)
        self.input_writer = AnnAGNPSInputWriter(self.config)
        print(f"Configuration updated. Output folder is now: {self.config.output_folder}")

    def _check_outlet_coords(self):
        """Ensures outlet coordinates are set, fetching from DB if needed."""
        if self.config.outlet_x is None or self.config.outlet_y is None:
            if self.config.thuc_id and self.config.reach_id:
                print(f"Fetching outlet x,y from THUC {self.config.thuc_id}, Reach {self.config.reach_id}")
                x, y = self.repository.get_outlet_xy_from_thuc_id_and_reach_id(self.config.thuc_id, self.config.reach_id)
                self.config.outlet_x = x
                self.config.outlet_y = y
            else:
                raise UserWarning("Watershed has no outlet. Set outlet_x/outlet_y or thuc_id/reach_id.")
        
        if self.config.thuc_id is None:
             print(f"Fetching THUC ID from x,y: {self.config.outlet_x}, {self.config.outlet_y}")
             self.config.thuc_id = self.repository.get_thuc_id_by_xy(self.config.outlet_x, self.config.outlet_y)

    # --- Watershed Logic Methods ---
    # These methods perform calculations on dataframes
    
    def get_watershed_bounds(self, cells_geometry: gpd.GeoDataFrame, save: bool = True) -> gpd.GeoDataFrame:
        """Get the watershed outline from the cells geometry."""
        bounds = utils.get_bounds_from_cells(cells_geometry)
        if save:
            self.bounds = bounds
        return bounds
    
    def get_dominant_storm_type(self, scs_storm_types_gdf: gpd.GeoDataFrame, bounds: gpd.GeoDataFrame) -> int:
        """Computes dominant storm type."""
        return annagnps.compute_dominant_storm_type(scs_storm_types_gdf, bounds)
    
    def get_weighted_precip_zones_parameters(self, precip_zones_gdf: gpd.GeoDataFrame, bounds: gpd.GeoDataFrame) -> Tuple[float, float, float]:
        """Computes weighted precip zone parameters."""
        return annagnps.compute_weighted_precip_zones_parameters(precip_zones_gdf, bounds)
    
    def get_watershed_centroid_xy(self, bounds: gpd.GeoDataFrame) -> Tuple[float, float]:
        """Gets the centroid of the watershed bounds."""
        watershed_centroid = bounds.to_crs('epsg:3857').centroid.to_crs('epsg:4326')
        return watershed_centroid.x.to_list()[0], watershed_centroid.y.to_list()[0]

    # --- Main Orchestration Method ---
    
    def generate_annagnps_watershed_input_files(self, perform_data_checks: bool = True):
        """
        Main orchestration method.
        Queries data, processes it, and writes all input files.
        """
        start_time = time.time()
        cfg = self.config # Use a shorthand for config

        # 1. Load static assets
        print('Loading static layers...')
        nldas2_centroids = self.asset_loader.load_nldas2_centroids(cfg.path_to_nldas2_centroids)
        scs_storm_types = self.asset_loader.load_scs_storm_types(cfg.path_to_scs_storm_types)
        precip_zones = self.asset_loader.load_precip_zones(cfg.path_to_precip_zones)

        # 2. Create directory structure
        input_folders = self.input_writer.make_watershed_input_dirs()
        general_dir = input_folders['general']
        watershed_dir = input_folders['watershed']
        simulation_dir = input_folders['simulation']

        # 3. Query main watershed data from repository
        print('Querying watershed data...')
        cells_geometry, df_cells, cells_list = self.repository.query_cells(
            cfg.thuc_id, cfg.outlet_x, cfg.outlet_y, perform_data_checks
        )
        reaches_geometry, df_reaches, reaches_list = self.repository.query_reaches(
            cfg.thuc_id, cfg.outlet_x, cfg.outlet_y
        )

        # 4. Query dependent data
        print('Querying dependent data (Soil & Management)...')
        soil_ids_list = [x for x in df_cells['soil_id'].unique() if not pd.isna(x)]
        df_soil, df_soil_layers, df_raw_soil = self.repository.query_soil(soil_ids_list, perform_data_checks)

        mgmt_field_ids = df_cells['mgmt_field_id'].unique().tolist()
        df_mgmt_field = self.repository.query_management_field(mgmt_field_ids)
        
        mgmt_schedule_ids = df_mgmt_field['Mgmt_Schd_ID'].unique().tolist()
        df_mgmt_schd = self.repository.query_management_schedule(mgmt_schedule_ids)
        
        crop_ids = df_mgmt_schd['New_Crop_ID'].dropna().unique().tolist()
        df_mgmt_crop = self.repository.query_management_crop(crop_ids)
        df_mgmt_crop_growth = self.repository.query_management_crop_growth(crop_ids)
        
        non_crop_ids = df_mgmt_schd['New_Non-Crop_ID'].dropna().unique().tolist()
        df_mgmt_non_crop = self.repository.query_management_non_crop(non_crop_ids)
        
        oper_ids = df_mgmt_schd['Mgmt_Operation_ID'].dropna().unique().tolist()
        df_mgmt_oper = self.repository.query_management_operation(oper_ids)
        
        roc_ids = df_mgmt_schd['Curve_Number_ID'].dropna().unique().tolist()
        df_roc = self.repository.query_runoff_curve(roc_ids)

        # 5. Process Climate Data
        print('Processing climate data...')
        cells_geometry, secondary_climate_ids = self.climate_processor.identify_secondary_climate_ids(
            cells_geometry, nldas2_centroids
        )
        
        # Update df_cells with the new climate IDs
        if 'secondary_climate_file_id' in cells_geometry.columns:
            df_cells = df_cells.set_index('cell_id')
            df_cells.update(cells_geometry.set_index('cell_id')[['secondary_climate_file_id']])
            df_cells = df_cells.reset_index()

        climate_dataframes, climate_station_metadata = self.climate_processor.generate_climate_data(
            cells_geometry, secondary_climate_ids
        )

        # 6. Write Data Files to Disk
        print('Writing data files...')
        self.input_writer.write_gis_files(cells_geometry, reaches_geometry)
        
        self.input_writer.write_dataframe(watershed_dir / 'cell_data_section.csv', df_cells, float_format='%1.5f')
        self.input_writer.write_dataframe(watershed_dir / 'reach_data_section.csv', df_reaches, float_format='%1.5f')
        
        self.input_writer.write_dataframe(general_dir / 'soil_data.csv', df_soil)
        self.input_writer.write_dataframe(general_dir / 'soil_layers_data.csv', df_soil_layers)
        self.input_writer.write_dataframe(general_dir / 'raw_soil_data_gNATSGO.csv', df_raw_soil)
        
        self.input_writer.write_dataframe(general_dir / 'management_oper.csv', df_mgmt_oper)
        df_mgmt_schd_formatted = annagnps.format_mgmt_schedule_for_output(df_mgmt_schd)
        self.input_writer.write_dataframe(general_dir / 'management_schedule.csv', df_mgmt_schd_formatted)
        self.input_writer.write_dataframe(general_dir / 'crop_data.csv', df_mgmt_crop)
        self.input_writer.write_dataframe(general_dir / 'crop_growth.csv', df_mgmt_crop_growth)
        self.input_writer.write_dataframe(general_dir / 'non_crop.csv', df_mgmt_non_crop)
        self.input_writer.write_dataframe(general_dir / 'management_field.csv', df_mgmt_field)
        self.input_writer.write_dataframe(general_dir / 'runoffcurve.csv', df_roc)
        
        self.input_writer.write_climate_files(climate_dataframes, climate_station_metadata)

        # 7. Perform Watershed-Scale Logic
        print('Computing watershed global parameters...')
        bounds = self.get_watershed_bounds(cells_geometry, save=True)
        lon, lat = self.get_watershed_centroid_xy(bounds)
        main_storm_type = self.get_dominant_storm_type(scs_storm_types, bounds)
        r_fctr, ei_10, ei_dom = self.get_weighted_precip_zones_parameters(precip_zones, bounds)

        # 8. Write Control Files
        print('Writing control files...')
        self.watershed_data_dict = {
            'Wshd_Name': cfg.watershed_name,
            'Wshd_Description': cfg.watershed_description,
            'Wshd_Location': cfg.watershed_location,
            'Latitude': lat,
            'Longitude': lon
        }
        self.input_writer.write_control_file(watershed_dir / 'watershed_data.csv', self.watershed_data_dict)
        
        sim_period_data = cfg.simulation_period_data_dict.copy()
        sim_period_data.update({
            'Simulation_Begin_Year': int(cfg.start_date[:4]),
            'Simulation_Begin_Month': int(cfg.start_date[5:7]),
            'Simulation_Begin_Day': int(cfg.start_date[8:10]),
            'Simulation_End_Year': int(cfg.end_date[:4]),
            'Simulation_End_Month': int(cfg.end_date[5:7]),
            'Simulation_End_Day': int(cfg.end_date[8:10]),
            'Rainfall_Fctr': r_fctr,
            '10-Year_EI': ei_10,
            'EI_Number': ei_dom
        })
        self.input_writer.write_control_file(simulation_dir / 'sim_period.csv', sim_period_data)

        globfac_data = cfg.global_factors_flags_dict.copy()
        globfac_data['Wshd_Storm_Type_ID'] = main_storm_type
        self.input_writer.write_control_file(simulation_dir / 'globfac.csv', globfac_data)
        
        self.input_writer.write_control_file(simulation_dir / 'outopts_global.csv', cfg.output_options_global_dict)
        self.input_writer.write_control_file(simulation_dir / 'outopts_aa.csv', cfg.output_options_aa_dict)
        self.input_writer.write_control_file(simulation_dir / 'outopts_tbl.csv', cfg.output_options_tbl_dict)
        self.input_writer.write_control_file(simulation_dir / 'annaid.csv', cfg.annagnps_id_dict)

        df_outopts_rch = pd.DataFrame({'Reach_ID': cfg.selected_reaches_for_output or []})
        self.input_writer.write_dataframe(simulation_dir / 'outopts_rch.csv', df_outopts_rch)

        # 9. Write Master File
        print('Writing master file...')
        master_file = {
            'AnnAGNPS ID': get_relative_path(cfg.output_folder, simulation_dir / 'annaid.csv'),
            'Cell Data': get_relative_path(cfg.output_folder, watershed_dir / 'cell_data_section.csv'),
            'Crop Data': get_relative_path(cfg.output_folder, general_dir / 'crop_data.csv') if not df_mgmt_crop.empty else 'ignore',
            'Crop Growth Data': get_relative_path(cfg.output_folder, general_dir / 'crop_growth.csv') if not df_mgmt_crop_growth.empty else 'ignore',
            'Global IDs Factors and Flags Data': get_relative_path(cfg.output_folder, simulation_dir / 'globfac.csv'),
            'Management Field Data': get_relative_path(cfg.output_folder, general_dir / 'management_field.csv') if not df_mgmt_field.empty else 'ignore',
            'Management Operation Data': get_relative_path(cfg.output_folder, general_dir / 'management_oper.csv') if not df_mgmt_oper.empty else 'ignore',
            'Management Schedule Data': get_relative_path(cfg.output_folder, general_dir / 'management_schedule.csv') if not df_mgmt_schd.empty else 'ignore',
            'Non-Crop Data': get_relative_path(cfg.output_folder, general_dir / 'non_crop.csv') if not df_mgmt_non_crop.empty else 'ignore',
            'Reach Data': get_relative_path(cfg.output_folder, watershed_dir / 'reach_data_section.csv'),
            'Runoff Curve Number Data': get_relative_path(cfg.output_folder, general_dir / 'runoffcurve.csv') if not df_roc.empty else 'ignore',
            'Simulation Period Data': get_relative_path(cfg.output_folder, simulation_dir / 'sim_period.csv'),
            'Soil Data': get_relative_path(cfg.output_folder, general_dir / 'soil_data.csv'),
            'Soil Layer Data': get_relative_path(cfg.output_folder, general_dir / 'soil_layers_data.csv'),
            'Watershed Data': get_relative_path(cfg.output_folder, watershed_dir / 'watershed_data.csv'),
            'Output Options - Global': get_relative_path(cfg.output_folder, simulation_dir / 'outopts_global.csv'),
            'Output Options - AA': get_relative_path(cfg.output_folder, simulation_dir / 'outopts_aa.csv'),
            'Output Options - TBL': get_relative_path(cfg.output_folder, simulation_dir / 'outopts_tbl.csv'),
            'Output Options - Reach': get_relative_path(cfg.output_folder, simulation_dir / 'outopts_rch.csv'),
            'CLIMATE DATA - DAILY': get_relative_path(cfg.output_folder, input_folders['climate'] / 'climate_daily.csv'),
            'CLIMATE DATA - STATION': get_relative_path(cfg.output_folder, input_folders['climate'] / 'climate_station.csv')
        }
        self.master_file_dict = master_file
        self.input_writer.write_master_file(self.master_file_dict)

        end_time = time.time()
        print(f'Finished in {round(end_time - start_time, 2)} seconds')
        print(f'Output folder: {self.config.output_folder}')

